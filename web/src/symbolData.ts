// Merge aliases instead of duplicating e.g. Ω/omega and θ/theta in results.
export const SYMBOLS: readonly (readonly [string, string])[] = [...[...COMMON_SYMBOLS, ...EXTRA_SYMBOLS, ...greek, ...scripts, ...accents, ...punctuation].reduce((entries, [symbol, keywords]) => {
  entries.set(symbol, `${entries.get(symbol) ?? ""} ${keywords}`.trim());
  return entries;
}, new Map<string, string>())];

export function searchSymbols(query: string) {
  const normalized = query.trim().toLowerCase().normalize("NFKD").replace(/[\u0300-\u036f]/g, "");
  const exact = SYMBOLS.find(([symbol]) => symbol === query.trim());
  if (exact) return [exact];
  const tokens = normalized.split(/\s+/).filter(Boolean);
  const unicode = /^u\+([\da-f]{1,6})$/i.exec(query.trim());
  if (unicode) {
    const code = parseInt(unicode[1], 16);
    if (code >= 0x20 && code <= 0x10ffff && !(code >= 0xd800 && code <= 0xdfff))
      return [[String.fromCodePoint(code), `Unicode U+${unicode[1].toUpperCase()}`]] as const;
    return [];
  }
  return SYMBOLS.filter(([symbol, keywords]) => symbol === query.trim() || tokens.every((token) => `${symbol} ${keywords}`.toLowerCase().normalize("NFKD").replace(/[\u0300-\u036f]/g, "").includes(token)));
}
