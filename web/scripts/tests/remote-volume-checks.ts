import type { Page } from "playwright";
import { openSettings, openMenu, closeMenu } from "./settings-helpers";
export async function checkRemoteVolume(page: Page) {
  const assert = (condition: unknown, message: string) => { if (!condition) throw Error(message); };
  const fixture = (code: string) => page.evaluate(`window.fixture.${code}`);
  const pad = page.getByLabel(/Trackpad\. Tap to click/);
  const key = async (key: string) => { await pad.dispatchEvent("keydown", { key }); await pad.dispatchEvent("keyup", { key }); };
  const volume = (label: string) => page.getByRole("slider", { name: `${label} volume`, exact: true, includeHidden: true });
  const setVolume = async (label: string, value: number) => { await openMenu(page); await volume(label).fill(String(value)); await closeMenu(page); await page.waitForTimeout(180); };
  await fixture('reset("volume")');
  await key("AudioVolumeUp");
  assert(await volume("PC").inputValue() === "41", "Volume keys must adjust PC while the menu is closed");
  await page.waitForTimeout(60);
  assert(await volume("PC").inputValue() === "41", "Stale PC polling must not undo a key step");
  await page.waitForTimeout(100); await key("AudioVolumeDown");
  await page.getByRole("button", { name: "Function keys", exact: true }).click();
  await page.getByRole("button", { name: "Volume up", exact: true }).click();
  assert(await volume("PC").inputValue() === "41", "Fn volume keys must use the menu slider's optimistic value");
  await page.getByRole("button", { name: "Volume down", exact: true }).click();
  await page.getByRole("button", { name: "Function keys", exact: true }).click();
  await page.waitForTimeout(250);
  await fixture("addTV()"); await fixture("volumeWrites.splice(0)");
  await openMenu(page); await page.getByRole("button", { name: "Select TV audio", exact: true }).click(); await closeMenu(page);
  for (let i = 0; i < 8; i++) await key("AudioVolumeUp");
  assert(await volume("TV").inputValue() === "20", "Rapid keys must accumulate against optimistic TV volume");
  await page.waitForTimeout(250);
  const writes = await fixture("volumeWrites") as { target: string; value: number }[];
  assert(writes.at(-1)?.value === 20 && writes.every(item => item.target === "fixture-tv") && writes.length < 8, "Slow TV writes must coalesce against the selected target");
  await setVolume("TV", 100); await key("AudioVolumeUp");
  assert(await volume("TV").inputValue() === "100", "TV volume must clamp at 100");
  await setVolume("TV", 0); await key("AudioVolumeDown");
  assert(await volume("TV").inputValue() === "0", "TV volume must clamp at zero");
  await openMenu(page); await page.getByRole("button", { name: "Select PC audio", exact: true }).click(); await closeMenu(page);
  await key("AudioVolumeUp"); assert(await volume("PC").inputValue() === "41", "Selecting PC must route subsequent volume keys to PC");
  assert(!(await fixture("log") as { key?: string }[]).some(item => item.key === "AudioVolumeUp" || item.key === "AudioVolumeDown"), "Redirected volume keys must not leak into OS input");
  await setVolume("PC", 40); await fixture("removeTV()");
  await openSettings(page); await page.getByRole("tab", { name: "Trackpad", exact: true }).click();
  await page.getByRole("switch", { name: "Volume keys control selected output", exact: true }).uncheck();
  await page.getByRole("button", { name: "Back to keyboard", exact: true }).click();
  await fixture('reset("volume")'); await key("AudioVolumeDown");
  assert((await fixture("log") as { key?: string }[]).filter(item => item.key === "AudioVolumeDown").length === 2, "Opting out must restore native OS volume keys");
}
